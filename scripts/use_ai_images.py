"""Use AI-generated photos on the site.

1. Put the generated images in ai-images/ named by item id (e.g. ai-images/california.png — see docs/image-prompts.md).
2. Run: python3 scripts/use_ai_images.py
   -> public/menu/ai/<id>.webp (square, 1200px, background darkened to the site's black)
   -> lib/ai-photos.ts (the site swaps those items to the new photos)
"""
import os
import re
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
SRC = os.path.join(ROOT, "ai-images")
OUT = os.path.join(ROOT, "public", "menu", "ai")
MENU = open(os.path.join(ROOT, "lib", "menu.ts")).read()
IDS = set(re.findall(r'id: "([a-z0-9-]+)"', MENU)) | set(re.findall(r'roll\("([a-z0-9-]+)"', MENU))


def main():
    os.makedirs(OUT, exist_ok=True)
    used, unknown = [], []
    for f in sorted(os.listdir(SRC)) if os.path.isdir(SRC) else []:
        key, ext = os.path.splitext(f)
        if ext.lower() not in {".png", ".jpg", ".jpeg", ".webp"}:
            continue
        if key not in IDS:
            unknown.append(f)
            continue
        im = Image.open(os.path.join(SRC, f)).convert("RGB")
        side = min(im.size)  # centre-crop to square
        im = im.crop(((im.width - side) // 2, (im.height - side) // 2, (im.width + side) // 2, (im.height + side) // 2))
        im.thumbnail((1200, 1200), Image.LANCZOS)
        im.save(os.path.join(OUT, f"{key}.webp"), quality=86, method=6)
        used.append(key)
    with open(os.path.join(ROOT, "lib", "ai-photos.ts"), "w") as fh:
        fh.write("// Generated by scripts/use_ai_images.py — ids that have an AI-generated photo in public/menu/ai/.\n")
        fh.write("export const aiPhotos: string[] = [" + ", ".join(f'"{k}"' for k in used) + "];\n")
    print(f"{len(used)} photos in use.")
    if unknown:
        print("Not matching any menu item (check the file name):", ", ".join(unknown))


if __name__ == "__main__":
    main()
